/**
 * Write worker/flags.generated.ts from the build's environment.
 *
 * The feature flags are BUILD variables (Workers Builds → Settings →
 * Build → Variables). next.config.mjs inlines them into the pages; this
 * writes the same values into the Worker, so one switch controls both
 * the UI and the endpoint (REFACTOR_AUDIT C17). Same rule as
 * lib/flags.ts: only the exact string "true" is on.
 *
 * Runs first in `npm run build` and `npm run typecheck`. The output is
 * gitignored: it describes one build, not the source.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { isPreviewBuild } from "./is-preview.mjs";

const on = (name) => process.env[name] === "true";
const automations = on("FEATURE_AUTOMATIONS");

const flags = {
  automations,
  automationsDemo: automations && on("FEATURE_AUTOMATIONS_DEMO"),
  voice: on("FEATURE_VOICE"),
};

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "worker", "flags.generated.ts");
writeFileSync(
  out,
  `// Generated by scripts/worker-flags.mjs. Do not edit; do not commit.\n` +
    `export const flags = ${JSON.stringify(flags)} as const;\n` +
    `/** Built from a non-main branch (scripts/is-preview.mjs). */\n` +
    `export const PREVIEW_BUILD = ${isPreviewBuild()};\n`
);
console.log(`[worker-flags] ${JSON.stringify(flags)}${isPreviewBuild() ? " (preview)" : ""}`);
